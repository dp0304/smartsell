#!/bin/sh
set -eu

# The postgres image runs this once over its local socket during cluster init.
export SMARTSELL_BACKGROUND_PASSWORD="${SMARTSELL_BACKGROUND_PASSWORD:-}"
psql -X --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" --set ON_ERROR_STOP=1 <<'SQL'
\getenv migration_password SMARTSELL_MIGRATION_PASSWORD
\getenv runtime_password SMARTSELL_RUNTIME_PASSWORD
\getenv background_password SMARTSELL_BACKGROUND_PASSWORD
SELECT :'background_password' <> '' AS provision_background \gset

BEGIN;
CREATE ROLE smartsell_request NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION;
CREATE ROLE smartsell_background NOLOGIN NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION;
CREATE ROLE app_owner LOGIN NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION PASSWORD :'migration_password';
CREATE ROLE app_rw LOGIN INHERIT NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION PASSWORD :'runtime_password';
GRANT smartsell_request TO app_rw;
REVOKE ALL ON DATABASE :"DBNAME" FROM PUBLIC;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO app_owner;
GRANT CONNECT, CREATE ON DATABASE :"DBNAME" TO app_owner;
GRANT CONNECT ON DATABASE :"DBNAME" TO app_rw;
\if :provision_background
CREATE ROLE app_background LOGIN INHERIT NOSUPERUSER NOBYPASSRLS NOCREATEROLE NOCREATEDB NOREPLICATION PASSWORD :'background_password';
GRANT smartsell_request, smartsell_background TO app_background;
GRANT CONNECT ON DATABASE :"DBNAME" TO app_background;
\endif
COMMIT;
SQL
