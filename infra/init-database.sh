#!/bin/sh
set -eu

[ -n "${APP_DB_PASSWORD:-}" ] && [ -n "${MIGRATION_DB_PASSWORD:-}" ]
psql -X -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" \
  --set=app_pass="$APP_DB_PASSWORD" --set=owner_pass="$MIGRATION_DB_PASSWORD" <<'SQL'
CREATE ROLE app_owner LOGIN NOSUPERUSER NOBYPASSRLS NOINHERIT PASSWORD :'owner_pass';
CREATE ROLE app_rw LOGIN NOSUPERUSER NOBYPASSRLS NOINHERIT PASSWORD :'app_pass';
REVOKE CREATE ON SCHEMA public FROM PUBLIC;
GRANT CONNECT ON DATABASE :DBNAME TO app_owner, app_rw;
GRANT CREATE ON DATABASE :DBNAME TO app_owner;
SQL
