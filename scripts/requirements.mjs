function caseTitles(call, title) {
  if (ts.isStringLiteralLike(title)) return [title.text];
  // Index cases generated by a for-of over literal fixture values.
  const loop = call.parent.parent;
  if (!ts.isTemplateExpression(title) || !ts.isExpressionStatement(call.parent) || !ts.isForOfStatement(loop)
      || !ts.isVariableDeclarationList(loop.initializer) || !ts.isArrayLiteralExpression(loop.expression)) return [];
  const name = loop.initializer.declarations[0]?.name;
  const spans = title.templateSpans;
  if (!name || !ts.isIdentifier(name) || !spans.every(({ expression }) => ts.isIdentifier(expression) && expression.text === name.text)) return [];
  return loop.expression.elements.filter(ts.isStringLiteralLike).map(value =>
    title.head.text + spans.map(span => value.text + span.literal.text).join(''));
}

function testCases(path) {
  const source = ts.createSourceFile(path, read(path), ts.ScriptTarget.Latest, true);
  const cases = [];
  function visit(node) {
    if (ts.isCallExpression(node)) {
      const { expression: callee, arguments: [title, ...args] } = node;
      const direct = ts.isIdentifier(callee) && /^(test|it)$/.test(callee.text);
      const each = ts.isCallExpression(callee) && ts.isPropertyAccessExpression(callee.expression)
        && callee.expression.name.text === 'each' && ts.isIdentifier(callee.expression.expression)
        && /^(test|it)$/.test(callee.expression.expression.text);
      const callback = args.at(-1);
      const named = callback && ts.isIdentifier(callback) && source.statements.some(statement =>
        ts.isFunctionDeclaration(statement) && statement.name?.text === callback.text && statement.body);
      if ((direct || each) && title && callback && (ts.isArrowFunction(callback) || ts.isFunctionExpression(callback) || named)) {
        const line = source.getLineAndCharacterOfPosition(node.getStart(source)).line + 1;
        for (const name of caseTitles(node, title)) cases.push({ title: name, line });
      }
    }
    ts.forEachChild(node, visit);
  }
  visit(source);
  return cases;
}

function evidenceLink(ref, id) {
  assert(surfaces.includes(ref.surface), `Invalid surface for ${id}`);
  assert(['pass', 'fail'].includes(ref.result), `Invalid result for ${id}`);
  assert.match(ref.file, /^(?:apps|packages|tests|infra)\/[\w./-]+\.(?:[cm]?[jt]s|sh)$/);
  assert(!ref.file.split('/').includes('..'), `Invalid evidence path for ${id}`);
  assert(ref.assertion?.trim(), `Missing assertion for ${id}`);
  const selectors = ['case', 'testId', 'shellAssertion'].filter(key => Object.hasOwn(ref, key));
  assert(selectors.length === 1 && !Object.hasOwn(ref, 'line'), `Expected one stable source selector for ${id}`);
  const [selector] = selectors;
  const value = ref[selector];
  assert(typeof value === 'string' && value.trim(), `Empty source selector for ${id}`);
  const shell = ref.file.endsWith('.sh');
  assert.equal(shell, selector === 'shellAssertion', `Wrong source selector for ${ref.file} (${id})`);
  if (selector === 'testId') assert.match(value, /^[A-Z]{2}\d{2}-[A-Z0-9-]+$/);
  if (!sourceIndexes.has(ref.file)) sourceIndexes.set(ref.file, shell ? lines(ref.file) : testCases(ref.file));
  const matches = sourceIndexes.get(ref.file).filter(row => {
    if (shell) return row.text.trim() === value;
    return selector === 'case' ? row.title === value : row.title.startsWith(`[${value}] `);
  });
  assert.equal(matches.length, 1, `Missing or ambiguous source ${ref.file}:${value} for ${id}`);
  const { line } = matches[0];
  const stableLabel = selector === 'shellAssertion' ? `${ref.file.split('/').at(-1)}:${line}` : value.replaceAll('|', '\\|');
  const label = `${ref.surface}${ref.result === 'fail' ? '失敗' : ''} ${stableLabel}`;
  let link = sourceLink(ref.file, line, label);
  if (ref.report !== undefined) {
    assert.match(ref.report, /^docs\/acceptance\/[\w-]+-results\.md$/);
    assert(read(ref.report).trim(), `Empty evidence report for ${id}`);
    link += ` · [實跑紀錄](${ref.report.split('/').at(-1)})`;
  }
  return `${ref.assertion.replaceAll('|', '\\|')} ${link}`;
}

