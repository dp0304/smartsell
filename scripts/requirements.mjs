function section(source, heading) {
  const matches = source.filter(row => heading.test(row.text));
  assert.equal(matches.length, 1, `Expected one heading: ${heading}`);
  const start = matches[0];
  const depth = start.text.match(/^#+/)[0].length;
  const next = source.slice(start.line).find(row => new RegExp(`^#{1,${depth}} `).test(row.text));
  return source.slice(start.line, next ? next.line - 1 : undefined);
}

function rows(source, key, width) {
  return source.flatMap(({ text, line }) => {
    if (!text.startsWith('|')) return [];
    const cells = text.split(/(?<!\\)\|/).slice(1, -1).map(cell => cell.trim());
    const match = cells[key]?.match(width.pattern);
    if (!match) return [];
    assert.equal(cells.length, width.columns, `Unexpected column count at line ${line}: ${text}`);
    return [{ cells, line, id: match[1], name: match[2] }];
  });
}

