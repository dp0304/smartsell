export const defaultLanguage = 'zh-Hans';

export function isLanguagePreference(value) {
  return value === 'system' || value === 'zh-Hans' || value === 'zh-Hant';
}

export function negotiateLanguage(preference, preferredLanguages) {
  if (preference !== 'system') return preference;
  for (const tag of preferredLanguages) {
    let locale;
    try { locale = new Intl.Locale(tag.replaceAll('_', '-')); }
    catch { continue; }
    if (locale.language !== 'zh') continue;
    if (locale.script === 'Hans') return 'zh-Hans';
    if (locale.script === 'Hant') return 'zh-Hant';
    if (locale.script) continue;
    if (['TW', 'HK', 'MO'].includes(locale.region)) return 'zh-Hant';
    if (!locale.region || ['CN', 'SG', 'MY'].includes(locale.region)) return 'zh-Hans';
  }
  return defaultLanguage;
}

export function translate(language, key, ...values) {
  const copy = language === 'zh-Hant' && Object.hasOwn(traditional, key) ? traditional[key] : key;
  return values.length ? copy.replace(/\{(\d+)\}/g, (placeholder, index) => values[index] ?? placeholder) : copy;
}
